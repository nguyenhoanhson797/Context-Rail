type IconProps = SVGProps<SVGSVGElement> & { size?: number; strokeWidth?: number };
type Node = readonly [string, Record<string, string | number>, (readonly [string, Record<string,string | number>])[]?];
function legacyIcon(name: string, node: Node) {
  return function Icon({ size=16, strokeWidth=1.8, className='', ...props }: IconProps) {
    const children=node[0]==='svg' ? node[2] ?? [] : [node];
    const kebab=name.replace(/([a-z0-9])([A-Z])/g,'$1-$2').toLowerCase();
    return <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={strokeWidth} strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" className={'i lucide lucide-' + kebab + ' ' + className} {...props}>{children.map(([tag,attrs],i)=>createElement(tag,{...attrs,key:i}))}</svg>;
  };
}
